"""O4: KV-cached decoding, compiled — ms/token against context length, three ways.

For R2's 4M transformer (learned positions) and 25M RoPE transformer, at context lengths C
(the static cache / buffer length) and batch sizes B: prefill a prompt of C - G tokens, then
generate G tokens greedily with

- ``recompute``: no cache, one compiled forward pass over [B, C] per token;
- ``cached``:    a jitted one-token step over a preallocated cache, called from Python;
- ``loop``:      the same step inside ``lax.fori_loop``, the whole generation one program.

Recorded per row: steady ms per generated step (compile excluded, median of ``--repeats``),
compile seconds, prefill ms, XLA's compiled memory and its "bytes accessed" estimate for one
step, and the bandwidth arithmetic: the bytes a step must read (fp16 matmul weights plus the
whole static cache) and the time those take at the T4's 320 GB/s. Weights are random: the
cost of a step does not depend on their values. The tokens generated by the three modes are
compared (they must agree; float16 ties aside).

    python experiments/o4_decode/run.py --out runs/o4.json
"""

from __future__ import annotations

import argparse
import json
import platform
import time
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
from flax import nnx

from jaxexp import decode as D
from jaxexp import transformer as T

ROOT = Path(__file__).resolve().parents[2]
MODELS = {  # R2's shapes: (positional, width, depth, heads)
    "transformer-4M": ("learned", 256, 5, 4),
    "transformer-25M-rope": ("rope", 512, 8, 8),
}
T4_BANDWIDTH = 320e9  # bytes/s, NVIDIA's figure for the T4's GDDR6


def _stats(jitted, *args) -> dict:
    started = time.perf_counter()
    compiled = jitted.lower(*args).compile()
    seconds = time.perf_counter() - started
    cost = compiled.cost_analysis()
    cost = cost[0] if isinstance(cost, list | tuple) else cost
    memory = compiled.memory_analysis()
    return {
        "compile_seconds": seconds,
        "xla_flops": float(cost.get("flops", float("nan"))),
        "xla_bytes_accessed": float(cost.get("bytes accessed", float("nan"))),
        "temp_bytes": int(memory.temp_size_in_bytes),
        "argument_bytes": int(memory.argument_size_in_bytes),
    }


def _time(fn, repeats: int) -> float:
    """Median wall seconds of ``fn()`` (which must block), after one warm-up call."""
    fn()
    times = []
    for _ in range(repeats):
        started = time.perf_counter()
        fn()
        times.append(time.perf_counter() - started)
    return float(np.median(times))


def measure(name: str, context: int, batch: int, args) -> list[dict]:
    positional, width, depth, heads = MODELS[name]
    model = T.CharTransformer(256, width, heads, depth, context, positional=positional, rngs=nnx.Rngs(0))
    params = D.weights(model, compute_dtype=jnp.float16 if args.amp else None)
    steps = args.steps
    prompt = jax.random.randint(jax.random.key(1), (batch, context - steps), 0, 256)
    base = {
        "model": name,
        "context": context,
        "batch": batch,
        "steps": steps,
        "prompt": context - steps,
        "amp": args.amp,
        "weight_bytes": D.weight_bytes(params),
        "cache_bytes": D.cache_bytes(params, batch, context),
    }
    # The bytes one cached step must read: every weight once, and the whole static cache
    # (attention reads all `context` slots and masks the unused ones).
    base["step_bytes_model"] = base["weight_bytes"] + base["cache_bytes"]
    base["step_ms_at_bandwidth"] = 1e3 * base["step_bytes_model"] / T4_BANDWIDTH
    rows, tokens = [], {}

    # recompute ----------------------------------------------------------------------
    if "recompute" in args.modes and context <= args.recompute_max:
        generate, next_token = D.make_recompute(params, context)
        buf = jnp.zeros((batch, context), prompt.dtype).at[:, : prompt.shape[1]].set(prompt)
        row = dict(base, mode="recompute", **_stats(next_token, params["w"], buf, prompt.shape[1]))
        per_step = _time(lambda: next_token(params["w"], buf, prompt.shape[1]).block_until_ready(), args.repeats)
        row["ms_per_step"] = 1e3 * per_step
        tokens["recompute"] = np.asarray(generate(prompt, args.check_steps))
        rows.append(row)

    # cached (Python loop over a jitted step) ----------------------------------------
    generate, (prefill_j, next_token) = D.make_cached(params, context)
    logits, cache = prefill_j(params["w"], prompt)
    tok = jnp.argmax(logits, -1).astype(prompt.dtype)
    prefill_ms = 1e3 * _time(lambda: jax.block_until_ready(prefill_j(params["w"], prompt)), args.repeats)
    if "cached" in args.modes:
        stats = _stats(next_token, params["w"], cache, tok, jnp.int32(prompt.shape[1]))

        def run_cached():
            c, t = D.empty_cache(params, batch, context), tok
            c = jax.tree.map(lambda a, b: a + b, c, cache)  # a fresh buffer (the step donates its cache)
            for pos in range(prompt.shape[1], context):
                t, c = next_token(params["w"], c, t, jnp.int32(pos))
            t.block_until_ready()

        total = _time(run_cached, args.repeats)
        rows.append(dict(base, mode="cached", prefill_ms=prefill_ms, ms_per_step=1e3 * total / steps, **stats))
        tokens["cached"] = np.asarray(generate(prompt, args.check_steps))

    # loop (fori_loop: prefill + generation in one program) ---------------------------
    if "loop" in args.modes:
        _, run = D.make_loop(params, context, steps)
        stats = _stats(run, params["w"], prompt)
        total = _time(lambda: run(params["w"], prompt).block_until_ready(), args.repeats)
        rows.append(dict(base, mode="loop", prefill_ms=prefill_ms, ms_per_step=1e3 * (total - prefill_ms / 1e3) / (steps - 1),
                         loop_total_ms=1e3 * total, **stats))
        _, run_check = D.make_loop(params, context, args.check_steps)
        tokens["loop"] = np.asarray(run_check(params["w"], prompt))

    agree = {f"{a}=={b}": float(np.mean(tokens[a] == tokens[b])) for a in tokens for b in tokens if a < b}
    for row in rows:
        row["token_agreement"] = agree
        row["achieved_GBps"] = row["step_bytes_model"] / (row["ms_per_step"] / 1e3) / 1e9
        print(f"[o4] {name:<21} C={context:<5} B={batch:<3} {row['mode']:<9} {row['ms_per_step']:8.3f} ms/step  "
              f"(bandwidth floor {row['step_ms_at_bandwidth']:.3f})  compile {row['compile_seconds']:5.1f}s  "
              f"temp {row['temp_bytes'] / 2**20:8.1f} MiB  agree {agree}", flush=True)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(ROOT / "runs" / "o4.json"))
    parser.add_argument("--models", nargs="+", default=list(MODELS), choices=list(MODELS))
    parser.add_argument("--contexts", nargs="+", type=int, default=[256, 512, 1024, 2048, 4096])
    parser.add_argument("--batches", nargs="+", type=int, default=[1, 8])
    parser.add_argument("--modes", nargs="+", default=["recompute", "cached", "loop"])
    parser.add_argument("--steps", type=int, default=128, help="generated tokens per timing run")
    parser.add_argument("--check-steps", type=int, default=32, help="tokens compared across modes")
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--recompute-max", type=int, default=4096, help="skip recompute above this context")
    parser.add_argument("--no-amp", dest="amp", action="store_false")
    # accepted for the Kaggle runner's common arguments
    parser.add_argument("--data-dir", default=None)
    parser.add_argument("--ml-ladder", default=None)
    args = parser.parse_args()
    report = {"device": str(jax.devices()[0]), "environment": {"python": platform.python_version(), "jax": jax.__version__},
              "settings": vars(args), "rows": []}
    for name in args.models:
        for context in args.contexts:
            for batch in args.batches:
                try:
                    report["rows"].extend(measure(name, context, batch, args))
                except Exception as error:  # noqa: BLE001  (out of memory is a result)
                    report["rows"].append({"model": name, "context": context, "batch": batch, "error": str(error)[:300]})
                    print(f"[o4] {name} C={context} B={batch} ERROR {str(error)[:120]}", flush=True)
                Path(args.out).parent.mkdir(parents=True, exist_ok=True)
                Path(args.out).write_text(json.dumps(report, indent=1))


if __name__ == "__main__":
    main()
